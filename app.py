"""PolicyLens: a small AI-powered checker for draft customer-support replies."""
from __future__ import annotations

import json
import os

from dotenv import load_dotenv
import streamlit as st

from checker import check_reply, validate_input

DEFAULT_MODEL = "openai/gpt-oss-20b"

load_dotenv()
GROQ_API_KEY = os.getenv("GROQ_API_KEY", "").strip()

st.set_page_config(page_title="PolicyLens | AI Reply Checker", page_icon="🛡️", layout="centered")
st.title("🛡️ Cynbit Al PolicyLens")
st.subheader("AI Reply Checker")
st.write(
    "Check whether a draft AI customer-support reply follows the company's official policy. "
    "PolicyLens highlights supported statements, possible contradictions, and claims that need evidence."
)
st.markdown("### How it works")
st.write(
    "1. Provide the official policy.\n"
    "2. Paste the customer's question and the AI-generated reply.\n"
    "3. The LLM compares the reply with the policy and returns a simple review label, possible issues, and a safer draft."
)
DEFAULT_POLICY = (
    "1. Customers can request a return within 14 days of delivery.\n"
    "2. The product must be unused and in its original packaging.\n"
    "3. Final-sale items cannot be returned.\n"
    "4. Approved refunds are processed within 5–7 business days."
)
DEFAULT_QUESTION = "I received my headphones 20 days ago. Can I return them and get a refund tomorrow?"
DEFAULT_DRAFT = (
    "Yes, you can return the headphones within 30 days, even if they have been used. "
    "Every item is eligible, and your refund will arrive tomorrow."
)

with st.sidebar:
    st.header("AI settings")
    st.caption("The Groq API key is loaded from the local .env file.")
    model = st.text_input(
        "Groq model ID",
        value=DEFAULT_MODEL,
        help="The default is openai/gpt-oss-20b. You can change this to another model available to your Groq account.",
    )

    st.caption("Never commit the .env file, API keys, screenshots containing keys, or real customer data to GitHub.")

st.markdown("### Enter the information")
policy = st.text_area(
    "1. Official company policy",
    value=DEFAULT_POLICY,
    height=150,
    help="Paste the approved policy or facts the reply must follow.",
)
question = st.text_area("2. Customer question", value=DEFAULT_QUESTION, height=85)
draft = st.text_area(
    "3. Draft AI reply to check",
    value=DEFAULT_DRAFT,
    height=120,
    help="Paste the answer generated by your chatbot or AI assistant.",
)

if st.button("Check reply", type="primary", use_container_width=True):
    errors = validate_input(policy, question, draft, model)
    if errors:
        for error in errors:
            st.error(error)
    elif not GROQ_API_KEY:
        st.error("Set GROQ_API_KEY in the local .env file before running the check.")
    else:
        try:
            with st.spinner("Checking the draft against the official policy..."):
                result = check_reply(policy, question, draft, GROQ_API_KEY, model.strip())
            st.session_state["policylens_result"] = result
        except (ValueError, RuntimeError) as exc:
            st.error(str(exc))
        except Exception as exc:  # Defensive UI boundary: do not expose raw request details.
            st.error(
                "The check could not be completed. Please verify your API key, model ID, "
                f"internet connection, and Groq service status. ({type(exc).__name__})"
            )

result = st.session_state.get("policylens_result")
if result:
    st.markdown("---")
    st.markdown("### Review result")
    status = result["status"]
    if status == "Supported":
        st.success(status)
    elif status == "Contradiction":
        st.error(status)
    else:
        st.warning(status)

    st.write(result["reason"])

    left, right = st.columns(2)
    with left:
        st.markdown("**Supported points**")
        if result["supported_points"]:
            for item in result["supported_points"]:
                st.write(f"• {item}")
        else:
            st.caption("No supported points identified.")
    with right:
        st.markdown("**Claims to check**")
        flagged = result["contradictions"] + result["unsupported_claims"]
        if flagged:
            for item in flagged:
                st.write(f"• {item}")
        else:
            st.caption("No specific issue identified by the model.")

    st.markdown("**Safer suggested reply**")
    st.write(result["safer_reply"])
    st.download_button(
        "Download review as JSON",
        data=json.dumps(result, indent=2, ensure_ascii=False),
        file_name="policylens_review.json",
        mime="application/json",
    )
    st.caption(
        "AI-generated assessment only. Review the supplied policy and wording yourself; "
        "do not treat this result as automatic approval."
    )

st.markdown("---")


st.caption(
    "The API key is loaded from the local .env file and sent to Groq for the check. "
    "The .env file is not committed to the project. "
    "Use fictional data for the demo; do not submit confidential customer information without permission."
)
